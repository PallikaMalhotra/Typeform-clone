"""ORM models: the database schema.

    users ─┬─< forms ─┬─< questions ─┬─< question_choices
           │          │              └─< logic_rules >── questions (destination)
           │          └─< responses ──< answers ──< answer_choices >── question_choices
"""

import uuid
from datetime import UTC, datetime
from typing import Any

from sqlalchemy import (
    JSON,
    Boolean,
    CheckConstraint,
    Column,
    DateTime,
    Float,
    ForeignKey,
    Index,
    Integer,
    String,
    Table,
    Text,
    UniqueConstraint,
)
from sqlalchemy.orm import Mapped, mapped_column, relationship

from .database import Base
from .question_types import FormStatus, LogicOperator, QuestionType


def utcnow() -> datetime:
    return datetime.now(UTC)


def new_uuid() -> str:
    return str(uuid.uuid4())


def _in(values: type) -> str:
    return ", ".join(f"'{v.value}'" for v in values)


class User(Base):
    """A form creator. Auth is out of scope, so one default creator is seeded."""

    __tablename__ = "users"

    id: Mapped[int] = mapped_column(Integer, primary_key=True)
    name: Mapped[str] = mapped_column(String(120))
    email: Mapped[str] = mapped_column(String(320), unique=True)
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=utcnow)

    forms: Mapped[list["Form"]] = relationship(back_populates="owner", cascade="all, delete-orphan")


class Form(Base):
    __tablename__ = "forms"
    __table_args__ = (
        CheckConstraint(f"status IN ({_in(FormStatus)})", name="ck_forms_status"),
        Index("ix_forms_owner_updated", "owner_id", "updated_at"),
    )

    id: Mapped[str] = mapped_column(String(36), primary_key=True, default=new_uuid)
    owner_id: Mapped[int] = mapped_column(ForeignKey("users.id", ondelete="CASCADE"))
    title: Mapped[str] = mapped_column(String(255))
    # Short public identifier used in the shareable link: /to/<slug>
    slug: Mapped[str] = mapped_column(String(16), unique=True, index=True)
    status: Mapped[str] = mapped_column(String(16), default=FormStatus.DRAFT.value)
    # Theme, welcome screen and thank-you screen. Validated by schemas.FormSettings.
    settings: Mapped[dict[str, Any]] = mapped_column(JSON, default=dict)
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=utcnow)
    updated_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=utcnow, onupdate=utcnow)
    published_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))

    owner: Mapped[User] = relationship(back_populates="forms")
    questions: Mapped[list["Question"]] = relationship(
        back_populates="form", cascade="all, delete-orphan", order_by="Question.position"
    )
    responses: Mapped[list["Response"]] = relationship(
        back_populates="form", cascade="all, delete-orphan", passive_deletes=True
    )

    @property
    def is_published(self) -> bool:
        return self.status == FormStatus.PUBLISHED.value


class Question(Base):
    __tablename__ = "questions"
    __table_args__ = (
        CheckConstraint(f"type IN ({_in(QuestionType)})", name="ck_questions_type"),
        Index("ix_questions_form_position", "form_id", "position"),
    )

    # Ids are generated by the builder (UUIDs) so it can reference questions,
    # e.g. as logic jump destinations, before they are saved.
    id: Mapped[str] = mapped_column(String(36), primary_key=True, default=new_uuid)
    form_id: Mapped[str] = mapped_column(ForeignKey("forms.id", ondelete="CASCADE"))
    position: Mapped[int] = mapped_column(Integer)
    type: Mapped[str] = mapped_column(String(32))
    title: Mapped[str] = mapped_column(Text, default="")
    description: Mapped[str | None] = mapped_column(Text)
    required: Mapped[bool] = mapped_column(Boolean, default=False)
    # Type-specific options (allow_multiple, steps, min/max...). See schemas.QuestionProperties.
    properties: Mapped[dict[str, Any]] = mapped_column(JSON, default=dict)

    form: Mapped[Form] = relationship(back_populates="questions")
    choices: Mapped[list["Choice"]] = relationship(
        back_populates="question", cascade="all, delete-orphan", order_by="Choice.position"
    )
    logic_rules: Mapped[list["LogicRule"]] = relationship(
        back_populates="question",
        cascade="all, delete-orphan",
        order_by="LogicRule.position",
        foreign_keys="LogicRule.question_id",
    )


class Choice(Base):
    """An option of a multiple choice or dropdown question."""

    __tablename__ = "question_choices"
    __table_args__ = (Index("ix_choices_question_position", "question_id", "position"),)

    id: Mapped[str] = mapped_column(String(36), primary_key=True, default=new_uuid)
    question_id: Mapped[str] = mapped_column(ForeignKey("questions.id", ondelete="CASCADE"))
    position: Mapped[int] = mapped_column(Integer)
    label: Mapped[str] = mapped_column(String(255))

    question: Mapped[Question] = relationship(back_populates="choices")


class LogicRule(Base):
    """A logic jump: "if <question> <operator> <value>, go to <destination>".

    Rules of a question are evaluated in `position` order and the first match wins.
    A NULL destination means "jump to the end" (the thank-you screen).
    With no matching rule the respondent simply moves to the next question.
    """

    __tablename__ = "logic_rules"
    __table_args__ = (
        CheckConstraint(f"operator IN ({_in(LogicOperator)})", name="ck_logic_rules_operator"),
    )

    id: Mapped[int] = mapped_column(Integer, primary_key=True)
    question_id: Mapped[str] = mapped_column(ForeignKey("questions.id", ondelete="CASCADE"), index=True)
    position: Mapped[int] = mapped_column(Integer, default=0)
    operator: Mapped[str] = mapped_column(String(16))
    # A choice id, "true"/"false" for yes/no, or a number for rating/number questions.
    value: Mapped[str] = mapped_column(String(255))
    destination_question_id: Mapped[str | None] = mapped_column(
        ForeignKey("questions.id", ondelete="CASCADE")
    )

    question: Mapped[Question] = relationship(back_populates="logic_rules", foreign_keys=[question_id])


class Response(Base):
    """One respondent's session on a form.

    It is created when the respondent starts answering, so responses with
    submitted_at = NULL are partial: that gives the completion rate.
    """

    __tablename__ = "responses"
    __table_args__ = (Index("ix_responses_form_submitted", "form_id", "submitted_at"),)

    id: Mapped[str] = mapped_column(String(36), primary_key=True, default=new_uuid)
    form_id: Mapped[str] = mapped_column(ForeignKey("forms.id", ondelete="CASCADE"))
    started_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=utcnow)
    updated_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=utcnow, onupdate=utcnow)
    submitted_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    user_agent: Mapped[str | None] = mapped_column(String(512))

    form: Mapped[Form] = relationship(back_populates="responses")
    answers: Mapped[list["Answer"]] = relationship(
        back_populates="response", cascade="all, delete-orphan", passive_deletes=True
    )

    @property
    def is_completed(self) -> bool:
        return self.submitted_at is not None


answer_choices = Table(
    "answer_choices",
    Base.metadata,
    Column("answer_id", ForeignKey("answers.id", ondelete="CASCADE"), primary_key=True),
    Column("choice_id", ForeignKey("question_choices.id", ondelete="CASCADE"), primary_key=True),
)


class Answer(Base):
    """The answer to one question within one response.

    The value is stored in a typed column depending on the question type:
    text_value (short/long text, email), number_value (number, rating),
    boolean_value (yes/no) or the answer_choices link table (choice types).
    """

    __tablename__ = "answers"
    __table_args__ = (UniqueConstraint("response_id", "question_id", name="uq_answers_response_question"),)

    id: Mapped[int] = mapped_column(Integer, primary_key=True)
    response_id: Mapped[str] = mapped_column(ForeignKey("responses.id", ondelete="CASCADE"))
    question_id: Mapped[str] = mapped_column(ForeignKey("questions.id", ondelete="CASCADE"), index=True)
    text_value: Mapped[str | None] = mapped_column(Text)
    number_value: Mapped[float | None] = mapped_column(Float)
    boolean_value: Mapped[bool | None] = mapped_column(Boolean)

    response: Mapped[Response] = relationship(back_populates="answers")
    question: Mapped[Question] = relationship()
    choices: Mapped[list[Choice]] = relationship(secondary=answer_choices, order_by=Choice.position)
